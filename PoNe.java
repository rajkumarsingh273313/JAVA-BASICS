
import java.util.*;

public class PoNe {

    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int a = sc.nextInt();

        if (a > 0) {
            System.out.println("It is a positive number");
        } else if (a < 0) {
            System.out.println("It is a negative number");
        } else {
            System.out.println("It is Zero! !!!!!!!");
        }
    }
}
